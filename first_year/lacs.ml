let rec profondeur lac =
  let rec vider lac bords =
    match bords with
    | [] -> ()
    | (i, j)::ll -> lac.(i).(j) <- 0 ; vider lac ll
  in
  let bords = ref [] in
  let largeur = Array.length lac.(0) in
  for i = 0 to Array.length lac - 1 do
    for j = 0 to largeur - 1 do
      if lac.(i).(j) = 1 &&
        lac.(i-1).(j) * lac.(i).(j+1) * lac.(i+1).(j) * lac.(i).(j-1) = 0
      then
        bords := (i, j)::!bords
    done
  done ;
  if !bords <> [] then (vider lac !bords ; (*affiche lac ; print_newline () ;*) profondeur lac + 1) else 0
;;

