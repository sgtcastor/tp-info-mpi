let affiche_ligne t = 
  for i = 0 to Array.length t - 1 do
    if i = 0 then print_int t.(0) else Printf.printf "-%d" t.(i)
  done;
  Printf.printf "\n"

let affiche tab =
 let n = Array.length tab in
 for i = 0 to n - 1 do
   affiche_ligne tab.(i)
 done;;

